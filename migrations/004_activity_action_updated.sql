-- Doska: действие «обновлено» в журнале активности.
-- Источник: docs/design/doska-architecture-2026-11-16.md, §3.7 и §4.1.
--
-- Правка полей задачи меняет не статус, а содержание. Прежний след писал
-- «смена статуса» с версией в полях «было/стало» — журнал врал. Отдельное
-- действие «updated» говорит правду: что именно изменилось, написано в
-- summary.
--
-- Правила: значение перечисления добавляется идемпотентно (IF NOT EXISTS),
-- файл применяется в одной транзакции. Значение, добавленное в этой
-- транзакции, использовать в ней же нельзя — поэтому файл только меняет
-- перечисление, а пишет след уже следующая транзакция.

ALTER TYPE activity_action ADD VALUE IF NOT EXISTS 'updated';
